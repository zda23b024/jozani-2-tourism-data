def fetch_one_id(cursor: Any, query: str, params: tuple[Any, ...]) -> int:
    cursor.execute(query, params)
    row = cursor.fetchone()
    if row is None:
        raise RuntimeError("Expected database row was not returned.")
    return int(row[0])


