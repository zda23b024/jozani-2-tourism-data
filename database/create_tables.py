def fetch_one_id(cursor: Any, query: str, params: tuple[Any, ...]) -> int:
    cursor.execute(query, params)
    row = cursor.fetchone()
    if row is None:
        raise RuntimeError("Expected database row was not returned.")
    return int(row[0])


def upsert_source(cursor: Any, row: dict) -> int:
    return fetch_one_id(
        cursor,
        """
        INSERT INTO sources (source_name, source_code, base_url, source_type, is_active, created_at, updated_at)
        VALUES (%s, %s, %s, %s, COALESCE(%s, TRUE), COALESCE(%s, NOW()), COALESCE(%s, NOW()))
        ON CONFLICT (source_code) DO UPDATE SET
            source_name = EXCLUDED.source_name,
            base_url = EXCLUDED.base_url,
            source_type = EXCLUDED.source_type,
            is_active = EXCLUDED.is_active,
            updated_at = NOW()
        RETURNING source_id
        """,
        (
            row.get("source_name"),
            row.get("source_code"),
            row.get("base_url"),
            row.get("source_type"),
            row.get("is_active"),
            row.get("created_at"),
            row.get("updated_at"),
        ),
    )


