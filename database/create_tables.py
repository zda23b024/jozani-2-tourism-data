def db_value(value: Any) -> Any:
    if value is None:
        return None
    try:
        if value is not value:
            return None
    except Exception:
        pass
    if isinstance(value, float) and math.isnan(value):
        return None
    if value in ("", [], {}):
        return None
    if isinstance(value, (dict, list, tuple)):
        return json.dumps(value, ensure_ascii=False)
    return value


def text_limit(value: Any, max_length: int) -> str | None:
    cleaned = db_value(value)
    if cleaned is None:
        return None
    text = str(cleaned).strip()
    if not text:
        return None
    return text[:max_length]


def date_value(value: Any) -> date | None:
    return parse_date(value)


def bool_value(value: Any) -> bool | None:
    if value in (None, ""):
        return None
    return bool(value)


def int_value(value: Any) -> int | None:
    if value in (None, ""):
        return None
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return None


def numeric_value(value: Any) -> float | None:
    if value in (None, ""):
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def time_value(value: Any) -> str | None:
    if value in (None, ""):
        return None
    text = str(value)
    import re

    match = re.search(r"([0-2]?\d:[0-5]\d)", text)
    if not match:
        return None
    return match.group(1)


def currency_code(value: Any) -> str | None:
    if value in (None, ""):
        return None
    text = str(value).strip().upper()
    return text[:3] if text else None


