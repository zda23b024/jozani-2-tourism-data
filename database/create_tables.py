def upsert_currency(cursor: Any, code: str | None) -> None:
    if not code:
        return
    cursor.execute(
        """
        INSERT INTO currencies (currency_code, currency_name, symbol)
        VALUES (%s, %s, %s)
        ON CONFLICT (currency_code) DO NOTHING
        """,
        (code, code, code),
    )


