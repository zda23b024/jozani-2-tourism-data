def fetch_existing_review_state_by_hotel(
    hotels: list[dict],
) -> dict[str, ReviewIncrementState]:
    if psycopg is None:
        return {}
    url = database_url()
    if not url:
        return {}

    ensure_database_exists()
    result: dict[str, ReviewIncrementState] = {}
    try:
        with psycopg.connect(url) as connection:
            create_database_tables(connection)
            with connection.cursor() as cursor:
                for hotel in hotels:
                    hotel_id = hotel.get("hotel_id")
                    if hotel_id in (None, ""):
                        continue
                    hotel_id_text = str(hotel_id)
                    cursor.execute(
                        """
                        SELECT r.source_review_id, r.review_date
                        FROM reviews r
                        JOIN place_source_records psr ON psr.place_source_id = r.place_source_id
                        JOIN sources s ON s.source_id = psr.source_id
                        WHERE s.source_code = 'BOOKING' AND psr.source_place_id = %s
                        """,
                        (hotel_id_text,),
                    )
                    rows = cursor.fetchall()
                    source_review_ids = {str(row[0]) for row in rows if row and row[0]}
                    parsed_dates = [
                        parsed
                        for row in rows
                        if len(row) > 1
                        for parsed in [parse_date(row[1])]
                        if parsed is not None
                    ]
                    result[hotel_id_text] = {
                        "source_review_ids": source_review_ids,
                        "newest_review_date": max(parsed_dates).isoformat() if parsed_dates else None,
                    }
            connection.commit()
    except Exception as error:
        print("Incremental review check skipped:", error)
        return {}

    print(
        "Existing review IDs loaded from PostgreSQL: "
        f"{sum(len(v.get('source_review_ids', set())) for v in result.values())}"
    )
    return result


def fetch_existing_review_ids_by_hotel(
    hotels: list[dict],
) -> dict[str, set[str]]:
    state_by_hotel = fetch_existing_review_state_by_hotel(hotels)
    return {
        hotel_id: state.get("source_review_ids", set())
        for hotel_id, state in state_by_hotel.items()
    }


def fetch_existing_review_ids_by_place_source_ids(
    place_source_ids: list[str],
) -> dict[str, set[str]]:
    if psycopg is None:
        return {}
    url = database_url()
    if not url:
        return {}

    ensure_database_exists()
    result: dict[str, set[str]] = {place_source_id: set() for place_source_id in place_source_ids if place_source_id}
    if not result:
        return {}

    def source_place_id_from_legacy(value: str) -> str:
        return value.rsplit(":", 1)[-1]

    try:
        with psycopg.connect(url) as connection:
            create_database_tables(connection)
            with connection.cursor() as cursor:
                for legacy_place_source_id in result:
                    cursor.execute(
                        """
                        SELECT r.source_review_id
                        FROM reviews r
                        JOIN place_source_records psr ON psr.place_source_id = r.place_source_id
                        JOIN sources s ON s.source_id = psr.source_id
                        WHERE s.source_code = 'BOOKING' AND psr.source_place_id = %s
                        """,
                        (source_place_id_from_legacy(legacy_place_source_id),),
                    )
                    result[legacy_place_source_id] = {
                        str(row[0])
                        for row in cursor.fetchall()
                        if row and row[0] not in (None, "")
                    }
            connection.commit()
    except Exception as error:
        print("Generic incremental review check skipped:", error)
        return {}

    print(
        "Existing generic review IDs loaded from PostgreSQL: "
        f"{sum(len(values) for values in result.values())}"
    )
    return result


def fetch_known_booking_places_for_reviews() -> tuple[list[dict], list[dict]]:
    if psycopg is None:
        print("Known place load skipped: psycopg is not installed.")
        return [], []

    url = database_url()
    if not url:
        print("Known place load skipped: database settings are missing.")
        return [], []

    ensure_database_exists()
    hotels: list[dict] = []
    attractions: list[dict] = []

    try:
        with psycopg.connect(url) as connection:
            create_database_tables(connection)
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    SELECT
                        psr.source_place_id,
                        psr.source_url,
                        psr.source_name,
                        psr.source_category,
                        psr.raw_json,
                        p.canonical_name,
                        pt.type_group
                    FROM place_source_records psr
                    JOIN sources s ON s.source_id = psr.source_id
                    JOIN places p ON p.place_id = psr.place_id
                    JOIN place_types pt ON pt.place_type_id = p.place_type_id
                    WHERE s.source_code = 'BOOKING'
                      AND psr.source_url IS NOT NULL
                      AND psr.is_active = TRUE
                    ORDER BY pt.type_group, psr.source_name
                    """
                )
                rows = cursor.fetchall()
            connection.commit()
    except Exception as error:
        print("Known place load failed:", error)
        return [], []

    for row in rows:
        (
            source_place_id,
            source_url,
            source_name,
            source_category,
            raw_json,
            canonical_name,
            type_group,
        ) = row
        raw = raw_json if isinstance(raw_json, dict) else {}
        if isinstance(raw_json, str):
            try:
                raw = json.loads(raw_json)
            except json.JSONDecodeError:
                raw = {}

        place = {
            **raw,
            "name": raw.get("name") or source_name or canonical_name,
            "property_url": raw.get("property_url") or source_url,
        }

        if type_group == "Accommodation":
            place["hotel_id"] = raw.get("hotel_id") or str(source_place_id)
            place["accommodation_type_id"] = raw.get("accommodation_type_id") or source_category
            place["sold_out"] = False
            hotels.append(place)
            continue

        if type_group in {"Attraction", "Activity"}:
            place["attraction_id"] = raw.get("attraction_id") or str(source_place_id)
            attractions.append(place)

    print(
        "Known Booking.com places loaded from PostgreSQL: "
        f"{len(hotels)} hotels, {len(attractions)} attractions"
    )
    return hotels, attractions
